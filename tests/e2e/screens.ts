// 360px 화면 점검: 9×9 퍼즐, 도감, 견본 집과 가구 창(리라·실타래·책장·액자)
import { chromium } from 'playwright';
const OUT = process.env.OUT ?? '/tmp';
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ viewport: { width: 360, height: 740 }, deviceScaleFactor: 2 });
  const p = await ctx.newPage();
  p.on('pageerror', (e) => console.log('pageerror', e.message));
  const shot = (n: string) => p.screenshot({ path: `${OUT}/s360-${n}.png` });
  await p.goto('http://localhost:4173/sudoku/');
  await p.getByRole('button', { name: /구글 계정으로 시작/ }).click();
  await p.fill('#email', 'dad@test'); await p.click('#go');
  await p.waitForSelector('.space');
  await p.getByRole('button', { name: '스도쿠', exact: true }).click();
  await shot('select');
  await p.locator('.size-card', { hasText: '9×9 어려움' }).click();
  await p.waitForSelector('.board');
  await p.locator('.board .cell:not(.given)').first().click();
  await p.getByRole('button', { name: '메모', exact: true }).click();
  for (const d of [1, 5, 9]) await p.getByRole('button', { name: new RegExp(`^${d} 넣기`) }).click();
  await p.getByRole('button', { name: '메모', exact: true }).click();
  await shot('puzzle9');
  await p.getByRole('button', { name: /^힌트, 남은/ }).click();
  for (let i = 0; i < 2; i++) await p.getByRole('button', { name: '더 알려 줘' }).click().catch(() => {});
  await p.screenshot({ path: `${OUT}/s360-hint9.png`, fullPage: true });
  await p.getByRole('button', { name: '나가기' }).click();
  await p.getByRole('button', { name: '도감', exact: true }).click();
  await p.waitForSelector('.dex-card');
  await p.waitForTimeout(800);
  await shot('dex');
  await p.locator('.dex-card').first().click();
  await p.getByRole('button', { name: '긴 이야기 읽기' }).click();
  await p.waitForTimeout(500);
  await shot('person');
  await p.keyboard.press('Escape');
  await p.getByRole('button', { name: '친구', exact: true }).click();
  await p.locator('.conn', { hasText: '견본 집' }).click();
  await p.waitForSelector('.visit .space');
  await p.waitForTimeout(600);
  await shot('sample');
  const tap = async (label: string) => { const l = p.locator(`.sprite[aria-label="${label}"]`).first(); await l.focus(); await l.press('Enter'); await p.waitForTimeout(500); };
  await tap('작은 리라'); await shot('lyre'); await p.keyboard.press('Escape');
  await tap('두루마리 책장'); await shot('bookcase'); await p.keyboard.press('Escape');
  await tap('신화 액자'); await shot('frame'); await p.keyboard.press('Escape');
  await tap('구름 침대'); await p.waitForTimeout(150); await shot('bed-react');
  await p.getByRole('tab', { name: '정원' }).click();
  await p.waitForTimeout(600);
  await tap('조개 분수'); await p.waitForTimeout(200); await shot('fountain');
  await b.close();
})();
