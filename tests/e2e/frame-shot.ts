import { chromium } from 'playwright';
const OUT = process.env.OUT ?? '/tmp';
(async () => {
  const b = await chromium.launch();
  const p = await b.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
  await p.goto('http://localhost:4173/sudoku/');
  await p.getByRole('button', { name: /구글 계정으로 시작/ }).click();
  await p.fill('#email', `frame${Date.now()}@test`); await p.click('#go');
  await p.waitForSelector('text=어떻게 불러 드릴까요?');
  await p.getByPlaceholder('예: 별빛 정원사').fill('훈제');
  await p.locator('.avatar-pick').nth(10).click();
  await p.waitForTimeout(500);
  await p.screenshot({ path: `${OUT}/f-onboard.png` });
  await p.getByRole('button', { name: '집 받기' }).click();
  await p.waitForSelector('.space'); await p.waitForTimeout(800);
  await p.screenshot({ path: `${OUT}/f-home.png` });
  await p.getByRole('button', { name: '도감', exact: true }).click();
  await p.waitForSelector('.dex-card'); await p.waitForTimeout(1000);
  await p.screenshot({ path: `${OUT}/f-dex.png` });
  await p.locator('.dex-card').first().click(); await p.waitForTimeout(600);
  await p.screenshot({ path: `${OUT}/f-person.png` });
  await b.close();
})();
